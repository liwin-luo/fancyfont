function isZalgoMark(codePoint: number): boolean {
  let lo = 0;
  let hi = ZALGO_RANGES.length - 1;
  while (lo <= hi) {
    const mid = (lo + hi) >> 1;
    const [start, end] = ZALGO_RANGES[mid];
    if (codePoint < start) hi = mid - 1;
    else if (codePoint > end) lo = mid + 1;
    else return true;
  }
  return false;
}

export interface ZalgoCleanResult {
  text: string;
  /** Combining marks and variation selectors that were stripped. */
  removed: number;
}

export function stripZalgo(text: string): ZalgoCleanResult {
  let removed = 0;
  let out = "";
  for (const char of text) {
    const codePoint = char.codePointAt(0) ?? 0;
    if (isZalgoMark(codePoint)) {
      removed++;
      continue;
    }
    out += char;
  }
  return { text: out, removed };
}
